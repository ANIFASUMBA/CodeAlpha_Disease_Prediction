import gradio as gr
import numpy as np

# Select the trained model to use for live predictions (e.g., XGBoost)
best_model = models["XGBoost"]

# Select 5 key medical features to keep the interface user-friendly
top_5_features = ['worst concave points', 'worst perimeter', 'worst area', 'worst radius', 'mean concave points']
feature_indices = [list(X.columns).index(feat) for feat in top_5_features]

# Mean values for all features to use as baseline defaults
default_values = X.mean().values.copy()

def predict_disease(concave_pts, perimeter, area, radius, mean_concave_pts):
    # Construct input array using defaults for other features
    input_data = default_values.copy()
    input_data[feature_indices[0]] = concave_pts
    input_data[feature_indices[1]] = perimeter
    input_data[feature_indices[2]] = area
    input_data[feature_indices[3]] = radius
    input_data[feature_indices[4]] = mean_concave_pts

    # Reshape for single sample prediction
    input_data = input_data.reshape(1, -1)

    # Prediction & Probabilities
    prediction = best_model.predict(input_data)[0]
    probabilities = best_model.predict_proba(input_data)[0]

    result_text = "Benign (Healthy / Low Risk)" if prediction == 1 else "Malignant (High Risk)"
    confidence = probabilities[prediction] * 100

    return f"**Prediction:** {result_text}\n\n**Confidence Level:** {confidence:.2f}%"

# Create Gradio Interface
interface = gr.Interface(
    fn=predict_disease,
    inputs=[
        gr.Slider(float(X['worst concave points'].min()), float(X['worst concave points'].max()), label="Worst Concave Points", value=float(X['worst concave points'].mean())),
        gr.Slider(float(X['worst perimeter'].min()), float(X['worst perimeter'].max()), label="Worst Perimeter", value=float(X['worst perimeter'].mean())),
        gr.Slider(float(X['worst area'].min()), float(X['worst area'].max()), label="Worst Area", value=float(X['worst area'].mean())),
        gr.Slider(float(X['worst radius'].min()), float(X['worst radius'].max()), label="Worst Radius", value=float(X['worst radius'].mean())),
        gr.Slider(float(X['mean concave points'].min()), float(X['mean concave points'].max()), label="Mean Concave Points", value=float(X['mean concave points'].mean())),
    ],
    outputs="markdown",
    title="🩺 Machine Learning Disease Prediction System",
    description="Adjust the medical feature parameters below to predict whether a tumor sample is Malignant or Benign using our trained XGBoost model."
)

interface.launch(share=True)

